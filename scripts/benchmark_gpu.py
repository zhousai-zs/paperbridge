def discover_smi():
    found = shutil.which('nvidia-smi')
    if found:
        return Path(found)
    root = Path(os.environ.get('SystemRoot', r'C:\Windows')) / 'System32' / 'DriverStore' / 'FileRepository'
    matches = list(root.glob('nv*/nvidia-smi.exe'))
    if not matches:
        raise RuntimeError('nvidia-smi was not found')
    return max(matches, key=lambda path: path.stat().st_mtime)


def smi_sample(executable):
    text = subprocess.check_output([str(executable),
        '--query-gpu=memory.used,memory.free,utilization.gpu,power.draw,temperature.gpu',
        '--format=csv,noheader,nounits'], text=True, timeout=5).strip()
    values = [part.strip() for part in text.split(',')]
    return {'timestamp': time.time(), 'used_mib': int(values[0]), 'free_mib': int(values[1]),
            'utilization_percent': int(values[2]), 'power_w': float(values[3]),
            'temperature_c': int(values[4])}


def run_cases(cases, output, backend):
    from paperbridge.core import convert
    configure()
    write_json(output / 'runner.json', {'pid': os.getpid()})
    started = time.perf_counter()
    documents = []
    with EngineSession(reuse=True) as engine:
        warm_started = time.perf_counter()
        _, warm_report = convert(ROOT / 'tests/corpus/fixture_en_1col.pdf', output / 'warmup',
                                 pages='1', engine=engine)
        warm_seconds = time.perf_counter() - warm_started
        measured_started = time.perf_counter()
        for case in cases:
            target, report = convert(case['source'], output / 'results', pages=case['pages'],
                                     chunk_size=2, engine=engine)
            if any(c['cached'] for c in report['chunks']) or not report['integrity']['assets_passed']:
                raise RuntimeError('Every measured chunk must be fresh with valid assets')
            stages = collections.Counter()
            chunks = []
            for chunk in report['chunks']:
                directory = target / 'chunks' / f"{chunk['index']:04}"
                stages.update(profile_log((directory / 'engine.log').read_text(encoding='utf-8', errors='replace')))
                chunks.append({'pages': chunk['pages'], 'timing': chunk['engine_timing']})
            documents.append({'name': case['name'], 'output': str(target),
                'pages': report['selected_pages'], 'seconds': report['elapsed_seconds'],
                'stage_seconds': dict(stages), 'chunks': chunks, 'counts': report['counts'],
                'status': report['status'], 'issues': report['issues'],
                'manifest': content_manifest(target)})
        measured_seconds = time.perf_counter() - measured_started
    import onnxruntime as ort
    write_json(output / 'run.json', {'backend': backend, 'ort_version': ort.__version__,
        'ort_file': ort.__file__, 'available_providers': ort.get_available_providers(),
        'warmup_seconds': round(warm_seconds, 3),
        'measured_seconds': round(measured_seconds, 3),
        'wall_seconds': round(time.perf_counter() - started, 3), 'documents': documents})


def provider_records(profile_dir):
    records = [json.loads(path.read_text(encoding='utf-8'))
               for path in sorted(profile_dir.glob('session-*.json'))]
    if not records:
        raise RuntimeError('CUDA run did not create a formula provider record')
    for record in records:
        if not record.get('actual_providers') or record['actual_providers'][0] != 'CUDAExecutionProvider':
            raise RuntimeError(f"CUDA activation failed: {record.get('actual_providers')}")
        counts = record.get('profile_provider_counts', {})
        if counts.get('CUDAExecutionProvider', 0) <= 0:
            raise RuntimeError('Formula profile contains no CUDA node events')
    return records


def compare_runs(runs):
    reference = {doc['name']: doc for doc in runs[0]['documents']}
    differences = []
    for run in runs[1:]:
        candidates = {doc['name']: doc for doc in run['documents']}
        if set(candidates) != set(reference):
            raise RuntimeError('Trial case coverage differs from the reference')
        for name, before in reference.items():
            after = candidates[name]
            for path in sorted(before['manifest'].keys() | after['manifest'].keys()):
                if before['manifest'].get(path) != after['manifest'].get(path):
                    differences.append({'run': run['run'], 'backend': run['backend'],
                                        'document': name, 'path': path})
    return differences


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cases', required=True, type=Path)
    parser.add_argument('-o', '--output', required=True, type=Path)
    parser.add_argument('--gpu-overlay', type=Path)
    parser.add_argument('--run', action='store_true', help=argparse.SUPPRESS)
    parser.add_argument('--backend', choices=('cpu', 'cuda'), default='cpu', help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        cases = load_cases(args.cases)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    args.output = args.output.resolve()
    if args.run:
        args.output.mkdir(parents=True, exist_ok=True)
        run_cases(cases, args.output, args.backend)
        return 0
    args.output.mkdir(parents=True, exist_ok=False)
    if args.gpu_overlay is None or not (args.gpu_overlay / 'onnxruntime').is_dir():
        parser.error('--gpu-overlay must contain the isolated GPU onnxruntime package')
    args.gpu_overlay = args.gpu_overlay.resolve()
    configure()
    shutil.copyfile(__file__, args.output / 'benchmark-source.py')
    hook_dir = args.output / 'hook'
    hook_dir.mkdir()
    (hook_dir / 'sitecustomize.py').write_text(HOOK_SOURCE, encoding='utf-8')
    smi = discover_smi()
    sources = [{**case, 'sha256': sha256(Path(case['source']))} for case in cases]
    models = {p.relative_to(model_home()).as_posix(): sha256(p)
              for p in model_home().rglob('*') if p.is_file() and p.suffix in ('.onnx', '.gguf', '.yml')}
    write_json(args.output / 'environment.json', {'cases': sources, 'models': models,
        'gpu_overlay': str(args.gpu_overlay), 'nvidia_smi': str(smi),
        'gpu_packages': {dist.metadata['Name']: dist.version for dist in importlib.metadata.distributions(path=[str(args.gpu_overlay)])},
        'git_commit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        'scope': 'Formula ONNX only; TF32 disabled; CPU fallback retained and measured. Production defaults are unchanged.'})
    schedule = ('cpu', 'cuda', 'cuda', 'cpu')
    runs = []
    for index, backend in enumerate(schedule, 1):
        name = f'{index:02}-{backend}'
        target = args.output / name
        profile_dir = target / 'cuda-profile'
        base_pythonpath = os.environ.get('PYTHONPATH', '')
        pythonpath = os.pathsep.join(str(path) for path in (hook_dir, args.gpu_overlay))
        if base_pythonpath:
            pythonpath += os.pathsep + base_pythonpath
        env = {**os.environ, 'MINERU_INTRA_OP_NUM_THREADS': '4',
               'MINERU_INTER_OP_NUM_THREADS': '1', 'MINERU_PROFILE_STAGES': '1',
               'MINERU_MODEL_SOURCE': 'local', 'HF_HUB_OFFLINE': '1', 'PYTHONUTF8': '1',
               'PYTHONPATH': pythonpath if backend == 'cuda' else base_pythonpath,
               'PAPERBRIDGE_FORMULA_CUDA_EXPERIMENT': '1' if backend == 'cuda' else '0',
               'PAPERBRIDGE_CUDA_PROFILE_DIR': str(profile_dir),
               'PAPERBRIDGE_CANCEL_FILE': str(args.output / f'{name}.cancel')}
        samples = []
        before = smi_sample(smi)
        with (args.output / f'{name}.log').open('w', encoding='utf-8') as stream:
            process = subprocess.Popen([sys.executable, str(Path(__file__).resolve()), '--run',
                '--cases', str(args.cases.resolve()), '-o', str(target), '--backend', backend],
                cwd=ROOT, env=env, stdout=stream, stderr=subprocess.STDOUT, **hidden_options())
            trial_started = time.monotonic()
            try:
                while process.poll() is None:
                    if time.monotonic() - trial_started >= 1800:
                        raise subprocess.TimeoutExpired(process.args, 1800)
                    try:
                        samples.append(smi_sample(smi))
                    except (OSError, ValueError, subprocess.SubprocessError):
                        pass
                    time.sleep(.5)
            except BaseException:
                Path(env['PAPERBRIDGE_CANCEL_FILE']).touch()
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    runner = target / 'runner.json'
                    if runner.exists():
                        process._paperbridge_pid = json.loads(runner.read_text(encoding='utf-8'))['pid']
                    terminate_tree(process)
                raise
        if process.returncode:
            raise RuntimeError(f'Trial failed ({process.returncode}); inspect {name}.log')
        run_path = target / 'run.json'
        run = json.loads(run_path.read_text(encoding='utf-8'))
        run['run'] = name
        run['gpu_samples'] = {'before': before, 'count': len(samples),
            'peak_used_mib': max((sample['used_mib'] for sample in samples), default=before['used_mib']),
            'peak_utilization_percent': max((sample['utilization_percent'] for sample in samples), default=0),
            'peak_power_w': max((sample['power_w'] for sample in samples), default=before['power_w'])}
        if backend == 'cuda':
            run['formula_sessions'] = provider_records(profile_dir)
        write_json(run_path, run)
        runs.append(run)
        print(json.dumps({'run': name, 'measured': run['measured_seconds'],
                          'peak_gpu_mib': run['gpu_samples']['peak_used_mib']}), flush=True)
        time.sleep(3)
    differences = compare_runs(runs)
    medians = {backend: statistics.median(run['measured_seconds'] for run in runs if run['backend'] == backend)
               for backend in ('cpu', 'cuda')}
    summary = {'runs': runs, 'median_measured_seconds': medians,
        'reduction_percent': round((1 - medians['cuda'] / medians['cpu']) * 100, 2),
        'saved_content_identical': not differences, 'differences': differences,
        'scope': 'Fresh same-page CPU/CUDA runs; Standard settings; persistent engine; formula ONNX only on CUDA; TF32 disabled. Hash equality is not semantic accuracy certification.'}
    write_json(args.output / 'benchmark.json', summary)
    print(json.dumps({'medians': medians, 'reduction_percent': summary['reduction_percent'],
                      'changed_files': len(differences)}, ensure_ascii=False), flush=True)
    return 0 if not differences else 2


if __name__ == '__main__':
    sys.exit(main())
